import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdtemp,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createAccount,createWorkspace,saveWorkspace} from '../lib/repository';
import {emptyWorkspace} from '../lib/workspace';
import {storeEvidence,readEvidence,discardEvidence} from '../lib/evidence-storage';
test('Local evidence retains legacy files and enforces membership, metadata and safe rollback',async()=>{
 const folder=await mkdtemp(join(tmpdir(),'copilot-evidence-'));
 process.env.STORAGE_DRIVER='sqlite';process.env.SQLITE_PATH=join(folder,'test.sqlite');process.env.UPLOAD_PATH=folder;
 const a=await createAccount(randomUUID()+'@example.test','A',null),b=await createAccount(randomUUID()+'@example.test','B',null);
 const workspace=emptyWorkspace(randomUUID(),'A');await createWorkspace(a.id,workspace);
 const id=randomUUID(),bytes=Buffer.from('Fictional evidence');
 await assert.rejects(storeEvidence(b.id,workspace.id,id,bytes),/denied/);
 await storeEvidence(a.id,workspace.id,id,bytes);
 await assert.rejects(readEvidence(a.id,workspace.id,id),/not found/);
 workspace.documents.push({id,taskId:'fixture',name:'fixture.txt',mime:'text/plain',size:bytes.length,uploadedAt:new Date().toISOString()});
 const saved=await saveWorkspace(a.id,workspace,0,'fixture-evidence');
 assert.deepEqual(await readEvidence(a.id,workspace.id,id),bytes);
 await assert.rejects(readEvidence(b.id,workspace.id,id),/denied/);
 await assert.rejects(discardEvidence(a.id,workspace.id,id),/Referenced/);
 await assert.rejects(storeEvidence(a.id,workspace.id,id,bytes),/EEXIST/);
 const orphan=randomUUID();await storeEvidence(a.id,workspace.id,orphan,bytes);await discardEvidence(a.id,workspace.id,orphan);
 const legacy=randomUUID();await writeFile(join(folder,legacy),bytes);saved.documents.push({...workspace.documents[0],id:legacy});await saveWorkspace(a.id,saved,1,'legacy-fixture');
 assert.deepEqual(await readEvidence(a.id,workspace.id,legacy),bytes);
 await assert.rejects(storeEvidence(a.id,workspace.id,'../escape',bytes),/not found/);
});
